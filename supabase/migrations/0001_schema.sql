-- F1 race pace MLOps: schema from docs/data_model.md
-- Run in the Supabase SQL editor (or `supabase db push`). Requires PostgreSQL 15+.
-- Public tables get a SELECT policy for `anon`; private tables have RLS on and no policy.

-- ---------------------------------------------------------------- reference

CREATE TABLE circuits (
    circuit_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text NOT NULL UNIQUE,
    country      text,
    circuit_type text NOT NULL CHECK (circuit_type IN ('street', 'permanent', 'hybrid'))
);

CREATE TABLE drivers (
    driver_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code      text NOT NULL UNIQUE,
    full_name text
);

CREATE TABLE teams (
    team_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    text NOT NULL UNIQUE
);

CREATE TABLE races (
    race_id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year              integer NOT NULL,
    round             integer NOT NULL,
    circuit_id        integer NOT NULL REFERENCES circuits,
    event_name        text,
    quali_date        date,
    race_date         date,
    is_sprint_weekend boolean NOT NULL DEFAULT false,
    UNIQUE (year, round)
);

-- The project's row: one driver in one race, with the team they drove for that weekend.
CREATE TABLE race_entries (
    entry_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    race_id   integer NOT NULL REFERENCES races,
    driver_id integer NOT NULL REFERENCES drivers,
    team_id   integer NOT NULL REFERENCES teams,
    UNIQUE (race_id, driver_id)
);

-- ------------------------------------------------------------- feature store

CREATE TABLE features (
    feature_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              text NOT NULL UNIQUE,
    feature_group     text NOT NULL
        CHECK (feature_group IN ('qualifying', 'practice', 'sprint', 'form', 'circuit', 'weather', 'context')),
    dtype             text NOT NULL,
    known_on_saturday boolean NOT NULL
);

CREATE TABLE feature_sets (
    feature_set_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version        text NOT NULL UNIQUE,
    schema_hash    text,
    created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE feature_set_items (
    feature_set_id integer NOT NULL REFERENCES feature_sets,
    feature_id     integer NOT NULL REFERENCES features,
    position       integer NOT NULL,
    PRIMARY KEY (feature_set_id, feature_id),
    UNIQUE (feature_set_id, position)
);

CREATE TABLE feature_values (
    entry_id        integer NOT NULL REFERENCES race_entries,
    feature_id      integer NOT NULL REFERENCES features,
    feature_set_id  integer NOT NULL REFERENCES feature_sets,
    value_num       double precision,
    value_text      text,
    computed_at     timestamptz NOT NULL DEFAULT now(),
    pipeline_run_id text,
    PRIMARY KEY (entry_id, feature_id, feature_set_id)
);

-- -------------------------------------------------------------------- models

CREATE TABLE model_versions (
    model_version_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mlflow_run_id          text NOT NULL UNIQUE,
    algorithm              text NOT NULL
        CHECK (algorithm IN ('baseline', 'ridge', 'elasticnet', 'rf', 'xgb', 'lgbm', 'catboost')),
    feature_set_id         integer NOT NULL REFERENCES feature_sets,
    trained_through_race_id integer REFERENCES races,
    is_shadow              boolean NOT NULL DEFAULT false,
    created_at             timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE champion_history (
    champion_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_version_id        integer NOT NULL REFERENCES model_versions,
    promoted_at             timestamptz NOT NULL DEFAULT now(),
    promoted_by             text NOT NULL CHECK (promoted_by IN ('manual', 'auto')),
    demoted_at              timestamptz,
    test_mae_improvement_pct double precision
);
-- At most one current champion (the row with demoted_at IS NULL).
CREATE UNIQUE INDEX one_current_champion ON champion_history ((true)) WHERE demoted_at IS NULL;

-- ------------------------------------------------- predictions, ground truth

CREATE TABLE prediction_runs (
    prediction_run_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    race_id           integer NOT NULL REFERENCES races,
    model_version_id  integer NOT NULL REFERENCES model_versions,
    dag_run_id        text,
    generated_at      timestamptz NOT NULL DEFAULT now(),
    is_late           boolean NOT NULL DEFAULT false
);

CREATE TABLE predictions (
    prediction_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_run_id        integer NOT NULL REFERENCES prediction_runs,
    entry_id                 integer NOT NULL REFERENCES race_entries,
    model_version_id         integer NOT NULL REFERENCES model_versions,
    predicted_pace_delta_pct double precision NOT NULL,
    baseline_pace_delta_pct  double precision,
    generated_at             timestamptz NOT NULL DEFAULT now(),
    UNIQUE (entry_id, model_version_id)
);

CREATE TABLE ground_truth (
    entry_id              integer PRIMARY KEY REFERENCES race_entries,
    actual_pace_delta_pct double precision,
    clean_laps            integer NOT NULL,
    is_valid_row          boolean NOT NULL,
    ingested_at           timestamptz NOT NULL DEFAULT now(),
    dag_run_id            text
);

-- ------------------------------------------------- evaluation and explanation

CREATE TABLE metrics (
    metric_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_version_id integer NOT NULL REFERENCES model_versions,
    race_id          integer REFERENCES races,   -- NULL for aggregates
    split            text NOT NULL CHECK (split IN ('train', 'test', 'walk_forward')),
    segment_type     text NOT NULL CHECK (segment_type IN ('overall', 'team', 'circuit_type')),
    segment_value    text,
    metric_name      text NOT NULL CHECK (metric_name IN ('mae', 'rmse', 'r2', 'pairwise_acc')),
    value            double precision NOT NULL,
    computed_at      timestamptz NOT NULL DEFAULT now(),
    -- NULLs count as equal so recomputing a metric is an upsert, not a duplicate
    UNIQUE NULLS NOT DISTINCT (model_version_id, race_id, split, segment_type, segment_value, metric_name)
);

CREATE TABLE shap_values (
    entry_id         integer NOT NULL REFERENCES race_entries,
    model_version_id integer NOT NULL REFERENCES model_versions,
    feature_id       integer NOT NULL REFERENCES features,
    shap_value       double precision NOT NULL,
    PRIMARY KEY (entry_id, model_version_id, feature_id)
);

-- ------------------------------------------ after the core (internal, private)

CREATE TABLE drift_reports (
    drift_report_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_version_id   integer NOT NULL REFERENCES model_versions,
    through_race_id    integer NOT NULL REFERENCES races,
    mae_change_pct     double precision,
    n_drifted_features integer,
    triggered_retrain  boolean NOT NULL DEFAULT false
);

CREATE TABLE drift_feature_results (
    drift_report_id integer NOT NULL REFERENCES drift_reports,
    feature_id      integer NOT NULL REFERENCES features,
    statistic       double precision,
    p_value         double precision,
    is_drifted      boolean NOT NULL,
    PRIMARY KEY (drift_report_id, feature_id)
);

-- Indexes for the foreign keys the DAGs and the page filter on.
CREATE INDEX ON race_entries (driver_id);
CREATE INDEX ON feature_values (feature_set_id);
CREATE INDEX ON feature_values (feature_id);
CREATE INDEX ON predictions (model_version_id);
CREATE INDEX ON prediction_runs (race_id);
CREATE INDEX ON metrics (race_id);

-- ------------------------------------------------------------ view for the page
-- Joins a private table (prediction_runs, for is_late). The view runs with its owner's
-- permissions (security_invoker = false) and exposes only the columns selected here.

CREATE VIEW prediction_results WITH (security_invoker = false) AS
SELECT r.year, r.round, d.code AS driver, t.name AS team,
       p.model_version_id,
       p.predicted_pace_delta_pct,
       g.actual_pace_delta_pct,
       p.predicted_pace_delta_pct - g.actual_pace_delta_pct      AS error,
       abs(p.predicted_pace_delta_pct - g.actual_pace_delta_pct) AS abs_error,
       g.is_valid_row,
       pr.is_late
FROM predictions p
JOIN prediction_runs pr USING (prediction_run_id)
JOIN race_entries e     USING (entry_id)
JOIN races r            USING (race_id)
JOIN drivers d          USING (driver_id)
JOIN teams t            ON t.team_id = e.team_id
LEFT JOIN ground_truth g USING (entry_id);   -- NULL until the race result is ingested

-- ------------------------------------------------------------------------ RLS
-- RLS is on for every table. Public tables get a SELECT policy for `anon` (the page's key).
-- Private tables get no policy and no grant: only the service key reads or writes them.

DO $$
DECLARE
    t text;
    public_tables  text[] := ARRAY['circuits', 'drivers', 'teams', 'races', 'race_entries', 'features',
                                   'model_versions', 'champion_history', 'predictions', 'ground_truth',
                                   'metrics', 'shap_values'];
    private_tables text[] := ARRAY['feature_sets', 'feature_set_items', 'feature_values', 'prediction_runs',
                                   'drift_reports', 'drift_feature_results'];
BEGIN
    FOREACH t IN ARRAY public_tables LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('CREATE POLICY "public read" ON %I FOR SELECT TO anon USING (true)', t);
        EXECUTE format('REVOKE ALL ON %I FROM anon', t);
        EXECUTE format('GRANT SELECT ON %I TO anon', t);
    END LOOP;
    FOREACH t IN ARRAY private_tables LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('REVOKE ALL ON %I FROM anon', t);
    END LOOP;
END $$;

REVOKE ALL ON prediction_results FROM anon;
GRANT SELECT ON prediction_results TO anon;
